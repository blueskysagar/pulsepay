package com.pulsepay.identity_service.security.token.impl;

import com.pulsepay.identity_service.security.token.RefreshTokenService;
import org.springframework.security.crypto.codec.Hex;
import org.springframework.stereotype.Service;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.SecureRandom;
import java.util.Base64;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;

@Service
public class RefreshTokenServiceImpl implements RefreshTokenService {
    private final SecureRandom secureRandom = new SecureRandom();
    /*
     * 32 bytes provide 256 bits of cryptographic entropy.
     *
     * The refresh token is a bearer credential, so we want a value
     * with an extremely large space of possible combinations that
     * an attacker cannot realistically guess.
     */
    private static final int TOKEN_BYTE_LENGTH = 32;
    @Override
    public String generateRefreshToken(){
        //It creates an empty 32-slot memory box (array) in Java, filled with zeros, ready to hold random data
        byte[] randomBytes = new byte[TOKEN_BYTE_LENGTH];
        /*
         * Fill every byte in the array with cryptographically secure
         * random data generated by SecureRandom.
         *
         * At this point, randomBytes changes from an empty byte array
         * into our unpredictable 256-bit refresh-token value.
         */
        secureRandom.nextBytes(randomBytes); //this generate the secret
        /*
         * Obtain a Base64 encoder that uses URL-safe characters.
         *
         * The refresh token will travel through HTTP, so we avoid characters
         * that can have special meanings in URLs or other transport contexts.
         */
        //Base64 is the class that converts random binary bytes to human readable format. Base
        //64 contains character like +=/ which when travels to Http will be corrupted, so we use
        //getUrlEncoder so that it replaces thoses character with hyphen and they can travel safely in http.
        Base64.Encoder encoder = Base64.getUrlEncoder();
        /*
         * Convert the cryptographically random bytes into a textual
         * Base64URL representation that can safely be returned to the client.
         */
        String refreshToken = encoder.encodeToString(randomBytes);
        /*
         * Return the raw refresh token to the caller.
         *
         * This value will eventually be sent to the client in the login
         * response, while only its SHA-256 hash will be persisted in PostgreSQL.
         */
        return refreshToken;


    }
    @Override
    public String hashRefreshToken(String refreshToken){
        /*
         * Create a SHA-256 message digest.
         *
         * MessageDigest is the Java API that performs the actual one-way
         * cryptographic hashing operation.
         */
        // "Create a variable that will hold the SHA-256 hashing engine."
        MessageDigest digest;
        //Go to security framework and hand me the cryptographic engine that performs SHA-256 hasing.
        try{
            digest = MessageDigest.getInstance("SHA-256");

        } catch (NoSuchAlgorithmException ex){

            /*
             * SHA-256 is expected to be available in every standard Java runtime.
             *
             * If it is unavailable, this is an internal application/runtime
             * failure, not a client error. We therefore fail the operation
             * instead of exposing cryptographic implementation details.
             */
            throw new IllegalStateException("Unable to hash refresh token",ex);
        }
        /*
         * Convert the refresh-token text into UTF-8 bytes because
         * MessageDigest hashes byte data rather than Java String objects.
         *
         * UTF-8 gives us a consistent byte representation of the token.
         */
        byte[] tokenBytes = refreshToken.getBytes(StandardCharsets.UTF_8);
        /*
         * Hash the refresh-token bytes using SHA-256.
         *
         * The result is a fixed 32-byte cryptographic digest.
         * We will store this digest in a textual representation
         * in the refresh-session record.
         */
        byte[] hashBytes = digest.digest(tokenBytes);
        /*
         * Convert the SHA-256 bytes into a hexadecimal String so the hash
         * can be stored and compared consistently in PostgreSQL.
         *
         * Each byte becomes two hexadecimal characters, so the resulting
         * SHA-256 representation is 64 characters long.
         */
        return HexFormat.of().formatHex(hashBytes);


    }


}
